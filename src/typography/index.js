export function textToShapes({
  text = 'LIQUID\nLIGHT',
  size = 140,
  tracking = 0,
  wordSpacing = 0,
  lineSpacing = 1.15,
  paragraphSpacing = 0,
  align = 'center',
  verticalAlign = 'center',
  boxWidth = 0, // 0 = no wrap
  x = 960,
  y = 540,
  rotation = 0,
  allCaps = false
} = {}) {
  const raw = String(text || '');
  const content = allCaps ? raw.toUpperCase() : raw;
  const lines = content.split('\n');
  const shapes = [];
  const advance = 0.82;
  const spaceAdvance = 0.45 + (wordSpacing / Math.max(1, size));

  // Simple wrapping if boxWidth > 0
  const processedLines = [];
  if (boxWidth > 0) {
    lines.forEach(line => {
      const words = line.split(/(\s+)/);
      let current = '';
      words.forEach(word => {
        const test = current + word;
        const width = measureWidth(test, size, tracking);
        if (width > boxWidth && current.trim()) {
          processedLines.push(current.trim());
          current = word.trimStart();
        } else {
          current = test;
        }
      });
      if (current.trim()) processedLines.push(current.trim());
    });
  } else {
    processedLines.push(...lines);
  }

  const lineHeight = size * lineSpacing;
  const totalHeight = processedLines.length * lineHeight + Math.max(0, processedLines.length - 1) * (paragraphSpacing || 0);
  let startY = y;
  if (verticalAlign === 'top') startY = y + totalHeight / 2;
  else if (verticalAlign === 'bottom') startY = y - totalHeight / 2;
  // center is default

  processedLines.forEach((line, li) => {
    const chars = [...line];
    let cursor = 0;
    const letterShapes = [];
    chars.forEach((ch, ci) => {
      const glyphKey = GLYPHS[ch] ? ch : (GLYPHS[ch.toUpperCase()] ? ch.toUpperCase() : '?');
      const glyph = GLYPHS[glyphKey] || GLYPHS['?'];
      if (glyph && glyph.length) {
        glyph.forEach(contour => {
          if (!contour.length) return;
          const points = contour.map(([px, py]) => [
            cursor + px * advance,
            (1 - py) * 0.92
          ]);
          letterShapes.push({
            points,
            closed: true,
            fill: true,
            width: 0,
            opacity: 1,
            char: ch,
            charIndex: ci,
            lineIndex: li
          });
        });
      }
      const isSpace = ch === ' ';
      cursor += (isSpace ? spaceAdvance : advance) + (tracking / size);
    });

    if (!letterShapes.length) return;
    const width = cursor - advance;
    let offsetX = 0;
    if (align === 'center') offsetX = -width / 2;
    else if (align === 'right') offsetX = -width;

    const lineY = startY - li * lineHeight - (li > 0 ? paragraphSpacing : 0);

    letterShapes.forEach(s => {
      const scaled = s.points.map(([px, py]) => [
        x + (px + offsetX) * size,
        lineY + (py - 0.5) * size
      ]);
      shapes.push({
        ...s,
        points: scaled,
        origin: [x, y]
      });
    });
  });

  // Apply rotation around center
  if (rotation) {
    const a = rotation * Math.PI / 180;
    const c = Math.cos(a), s = Math.sin(a);
    shapes.forEach(sh => {
      sh.points = sh.points.map(([px, py]) => [
        x + (px - x) * c - (py - y) * s,
        y + (px - x) * s + (py - y) * c
      ]);
    });
  }

  return shapes;
}

function measureWidth(str, size, tracking) {
  const advance = 0.82;
  let w = 0;
  for (const ch of str) {
    w += (ch === ' ' ? 0.45 : advance) + (tracking / size);
  }
  return w * size;
}

